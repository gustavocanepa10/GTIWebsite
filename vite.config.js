import { defineConfig } from "@lovable.dev/vite-tanstack-config";
import { fileURLToPath } from "node:url";
import { readFile, writeFile } from "node:fs/promises";
import { getPublicVideoFiles } from "./config/video-manifest.js";

const routeTreePath = fileURLToPath(new URL("./src/routeTree.gen.js", import.meta.url));

async function removeRouteTypeFooter() {
  // This TanStack Start version appends type registration even with disableTypes.
  const source = await readFile(routeTreePath, "utf8");
  const javascript = source.replace(/\nimport type \{ getRouter \}[\s\S]*$/, "\n");
  if (javascript !== source) await writeFile(routeTreePath, javascript);
}

// Keep Lovable's existing React, Tailwind, SSR and deployment integrations.
const lovableConfig = defineConfig({
  vite: {
    base: "/gtiwebsite/",
    define: {
      "import.meta.env.GTI_PUBLIC_VIDEO_FILES": JSON.stringify(getPublicVideoFiles()),
    },
    resolve: {
      alias: { "@": fileURLToPath(new URL("./src", import.meta.url)) },
    },
  },
  tanstackStart: {
    router: {
      disableTypes: true,
      generatedRouteTree: "routeTree.gen.js",
      routeTreeFileHeader: ["// Generated by TanStack Router. Do not edit manually."],
    },
    server: { entry: "server" },
    prerender: {
    enabled: true,
    crawlLinks: true,
    failOnError: true,
  filter: ({ path }) => {
    const pathname = path.split(/[?#]/)[0];

    // Ignora arquivos de mídia e outros recursos estáticos
    if (/\.(mp4|webm|mp3|png|jpg|jpeg|svg|ico|css|js)$/i.test(pathname)) {
      return false;
    }

    // Evita prerenderizar URLs com o prefixo duplicado
    if (pathname.startsWith("/gtiwebsite/")) {
      return false;
    }

    return true;
  },
},
  },
});

export default async (env) => {
  const config = await lovableConfig(env);
  // The Lovable preset hardcodes tsconfig.json. JavaScript uses the alias above.
  config.plugins = config.plugins
    .flat(Infinity)
    .filter((plugin) => plugin?.name !== "vite-tsconfig-paths");
  const generator = config.plugins.find((plugin) => plugin?.name === "tanstack:router-generator");
  for (const hook of ["configResolved", "watchChange"]) {
    const original = generator[hook];
    generator[hook] = async function (...args) {
      // Ignore our own cleanup writes so the watcher cannot regenerate in a loop.
      if (
        hook === "watchChange" &&
        args[0].replaceAll("\\", "/") === routeTreePath.replaceAll("\\", "/")
      ) {
        return;
      }
      await original.apply(this, args);
      await removeRouteTypeFooter();
    };
  }
  return config;
};
